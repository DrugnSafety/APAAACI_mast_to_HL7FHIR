import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require('/Users/mingyukang/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const root = path.dirname(fileURLToPath(import.meta.url));
const output = path.join(root, 'validation'); fs.mkdirSync(output, { recursive: true });
const q = JSON.parse(fs.readFileSync(path.join(root, 'survey_definition.json')));
const checks = [], errors = [], external = [], mutations = [];
function check(name, pass, detail = '') { checks.push({ name, pass: !!pass, detail }); if (!pass) errors.push(name + ': ' + detail); }
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--disable-component-update', '--disable-features=OptimizationGuideModelDownloading,OptimizationHints,MediaRouter'] });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true, reducedMotion: 'reduce' });
await context.route(/^https?:/, route => { external.push(route.request().url()); return route.abort(); });
const page = await context.newPage();
page.on('pageerror', e => errors.push(e.message));
page.on('request', request => { if (request.method() !== 'GET') mutations.push(request.method()); });
const open = () => page.goto(pathToFileURL(path.join(root, 'patient_satisfaction.html')).href);
const enter = async (respondent, material) => {
  await page.locator(`input[name=respondent][value=${respondent}]`).check();
  await page.locator(`input[name=material][value=${material}]`).check();
  await page.locator('#entry-next').click();
};
const download = async () => {
  if (!await page.locator('#done details').evaluate(e => e.open)) await page.locator('#done summary').click();
  const pending = page.waitForEvent('download');
  await page.locator('#download-response').click();
  const dl = await pending;
  const result = JSON.parse(fs.readFileSync(await dl.path(), 'utf8'));
  return result;
};
try {
  for (const file of ['index.html', 'implementation_guide.html', 'patient_satisfaction.html']) {
    await page.goto(pathToFileURL(path.join(root, file)).href);
    const headings = await page.locator('h1:visible').count();
    check(file + ' one visible title', headings === 1, String(headings));
    check(file + ' desktop width', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2));
    await page.setViewportSize({ width: 390, height: 844 });
    check(file + ' mobile width', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2));
    await page.setViewportSize({ width: 1440, height: 1000 });
  }
  await open();
  check('no preselected answers', await page.locator('input:checked').count() === 0);
  check('no real identifiers requested', await page.locator('input[type=text],input[type=tel],input[type=email],input[type=date]').count() === 0);
  await page.locator('#entry-next').click();
  check('missing entry stays on entry', await page.locator('#entry').isVisible() && await page.locator('#entry-error').isVisible());
  await enter('guardian', 'both');
  check('six rating items', await page.locator('#ratings fieldset').count() === 6);
  for (const item of q.items) {
    check(item.id + ' canonical wording', (await page.locator(`#ratings input[name=${item.id}]`).first().locator('xpath=ancestor::fieldset/legend').innerText()).includes(item.text));
    check(item.id + ' seven options', await page.locator(`input[name=${item.id}]`).count() === 7);
  }
  await page.locator('input[name=S1][value="5"]').check();
  await page.locator('input[name=S2][value=unable]').check();
  await page.locator('input[name=S3][value=skip]').check();
  await page.locator('input[name=S5][value="2"]').check();
  await page.locator('input[name=S6][value="4"]').check();
  const comment = '<img src=x onerror=alert(1)> 화면 예시 의견';
  await page.locator('#comment').fill(comment);
  check('comment has 300 character cap', await page.locator('#comment').getAttribute('maxlength') === '300');
  await page.locator('#ratings-next').click();
  check('safe comment review', (await page.locator('#review-content').innerText()).includes(comment) && await page.locator('#review-content img').count() === 0);
  check('blank answer remains optional', (await page.locator('#review-content').innerText()).includes('빈 답변'));
  await page.locator('#finish').click();
  check('completion does not claim transmission', (await page.locator('#done').innerText()).includes('병원에 전송하지 않았습니다'));
  const r = await download();
  check('preview export boundary', r.preview_only === true && r.transmitted_to_hospital === false);
  check('guardian recorded', r.respondent_type === 'guardian');
  check('numeric answer retained', r.answers.S1.value === 5 && r.answers.S6.value === 4);
  check('unable distinct', r.answers.S2.status === 'unable' && r.answers.S2.value === null);
  check('skip distinct', r.answers.S3.status === 'skip' && r.answers.S3.value === null);
  check('blank distinct', r.answers.S4.status === 'blank' && r.answers.S4.value === null);
  check('comment export retained', r.comment === comment);
  await page.locator('#restart').click();
  check('restart clears answers', await page.locator('input:checked').count() === 0 && await page.locator('#comment').inputValue() === '');
  await enter('patient_assisted', 'cardnews');
  await page.locator('input[name=S6][value="3"]').check();
  await page.locator('#comment').fill('이 답변은 미열람 분기에서 제외해야 합니다.');
  await page.locator('[data-back-entry]').first().click();
  await page.locator('input[name=material][value=neither]').check();
  await page.locator('#entry-next').click();
  check('nonviewer skips rating items', await page.locator('#nonviewer').isVisible() && !await page.locator('#ratings').isVisible());
  await page.locator('input[name=nonviewer_reason][value=access_problem]').check();
  await page.locator('#nonviewer-next').click();
  check('nonviewer review excludes hidden answers', !(await page.locator('#review-content').innerText()).includes('이 답변은'));
  await page.locator('#finish').click();
  const nr = await download();
  check('nonviewer export excludes hidden values', Object.values(nr.answers).every(a => a.status === 'not_viewed' && a.value === null) && nr.comment === null);
  check('nonviewer reason recorded', nr.nonviewer_reason === 'access_problem');
  check('assisted patient recorded', nr.respondent_type === 'patient_assisted');
  await page.locator('#restart').click();
  await enter('patient', 'report');
  await page.locator('input[name=S6][value="1"]').check();
  await page.locator('#ratings [data-exit]').click();
  check('exit clears responses', await page.locator('#stopped').isVisible() && await page.locator('input:checked').count() === 0);
  await page.locator('#restart-stopped').click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: path.join(output, 'survey_mobile.jpg'), type: 'jpeg', quality: 73 });
  await enter('patient', 'both');
  check('mobile ratings have no page overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2));
  check('mobile rating labels meet touch height', await page.locator('.ratings .choice').first().evaluate(e => e.getBoundingClientRect().height >= 44));
  await page.screenshot({ path: path.join(output, 'ratings_mobile.jpg'), type: 'jpeg', quality: 73 });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: path.join(output, 'ratings_desktop.jpg'), type: 'jpeg', quality: 73 });
  await page.emulateMedia({ media: 'print' });
  check('print shows complete blank questionnaire', await page.locator('.paper').isVisible() && await page.locator('.paper tbody tr').count() === 6);
  await page.pdf({ path: path.join(root, 'patient_satisfaction.pdf'), format: 'A4', printBackground: true, preferCSSPageSize: true, tagged: true });
  await page.emulateMedia({ media: 'screen' });
  check('no external network requests', external.length === 0, JSON.stringify(external));
  check('no network submission', mutations.length === 0, JSON.stringify(mutations));
  check('no browser persistence', await page.evaluate(() => localStorage.length === 0 && sessionStorage.length === 0));
} finally { await browser.close(); }
const result = { date: new Date().toISOString(), checks: checks.length, failures: errors.length, errors, external, mutations, results: checks, word_native_render: false };
fs.writeFileSync(path.join(output, 'browser_validation.json'), JSON.stringify(result, null, 2) + '\n');
console.log(JSON.stringify({ checks: checks.length, failures: errors.length, errors, external_requests: external.length, network_submissions: mutations.length }));
if (errors.length) process.exitCode = 1;
